"""TD 2, check of step 1 by Pair C at the merge: fixed 2-of-3 panel against 3-of-5 quorum on the twenty questions.

Usage (from the repository root):  python3 td2/C-routing/analyse_votes.py
Reads traces-td1.csv (real rows only) and reuses the proposal building of atelier-vote.py and the
vote_k_sur_n method of skeleton-multi-llm-en.py. The reference is compared after the decision.
Writes td2/C-routing/vote-td2.md and td2/C-routing/vote-td2.csv.
"""
import csv
import importlib.util
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]

spec = importlib.util.spec_from_file_location("atelier_vote", ROOT / "atelier-vote.py")
atelier = importlib.util.module_from_spec(spec)
sys.modules[spec.name] = atelier
spec.loader.exec_module(atelier)

PANEL_3 = list(atelier.PANEL)
PANEL_5 = PANEL_3 + [("groq", "openai/gpt-oss-20b"), ("openrouter", "dots-studio/dots-3-note-preview:free")]
SHORT = {"openai/gpt-oss-120b": "120B", "cohere/north-mini-code:free": "Cohere", "qwen/qwen3.8-27b": "Qwen",
         "openai/gpt-oss-20b": "20B", "dots-studio/dots-3-note-preview:free": "Dots"}


def decide(vote, rows, case, panel, k):
    atelier.PANEL = panel
    return vote(atelier.proposals_for(rows, case, "real"), k)


def describe(decision):
    if decision["consensus"]:
        return f"consensus {decision['value']} ({decision['votes']} votes)"
    return f"abstain (largest {decision['votes']})"


def main():
    with open(ROOT / "traces-td1.csv", encoding="utf-8", newline="") as f:
        rows = list(csv.DictReader(f))
    with open(ROOT / "reference-td1.csv", encoding="utf-8", newline="") as f:
        references = {r["case_id"]: int(r["revenue_cents"]) for r in csv.DictReader(f)}
    vote = atelier.load_vote()

    table = []
    for case in sorted(references):
        last = {}
        for row in rows:
            if row["case_id"] == case and row["nature"] == "real":
                last[row["model_requested"]] = row
        members = []
        for _, model in PANEL_5:
            row = last[model]
            shown = row["value"] if row["value"] else row["verdict"]
            members.append(f"{SHORT[model]} {shown}")
        d3 = decide(vote, rows, case, PANEL_3, 2)
        d5 = decide(vote, rows, case, PANEL_5, 3)
        ref = references[case]
        table.append({
            "case_id": case,
            "values_120B_Cohere_Qwen_20B_Dots": "; ".join(members),
            "panel_2_of_3": describe(d3),
            "panel_2_of_3_matches_reference": "-" if not d3["consensus"] else ("yes" if d3["value"] == ref else "NO"),
            "quorum_3_of_5": describe(d5),
            "quorum_3_of_5_matches_reference": "-" if not d5["consensus"] else ("yes" if d5["value"] == ref else "NO"),
            "reference": ref,
            "decision_changes": "yes" if (d3["consensus"], d3["value"]) != (d5["consensus"], d5["value"]) else "",
        })
    atelier.PANEL = PANEL_3

    out_dir = HERE
    with open(out_dir / "vote-td2.csv", "w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(table[0].keys()), lineterminator="\n")
        writer.writeheader()
        writer.writerows(table)
    lines = ["| Case | Values: 120B, Cohere, Qwen, 20B, Dots | 2-of-3 panel | OK | 3-of-5 quorum | OK | Reference | Changes |",
             "|---|---|---|---|---|---|---|---|"]
    for r in table:
        lines.append(f"| {r['case_id']} | {r['values_120B_Cohere_Qwen_20B_Dots']} | {r['panel_2_of_3']} | {r['panel_2_of_3_matches_reference']} | "
                     f"{r['quorum_3_of_5']} | {r['quorum_3_of_5_matches_reference']} | {r['reference']} | {r['decision_changes']} |")
    (out_dir / "vote-td2.md").write_text(
        "# TD 2 — 2-of-3 panel against 3-of-5 quorum on the TD 1 traces\n\n"
        "Generated by `td2/C-routing/analyse_votes.py` from `traces-td1.csv` (real rows, last attempt per model) and "
        "`reference-td1.csv`. Panel 2-of-3: 120B, Cohere, Qwen (fixed panel of `atelier-vote.py`). "
        "Quorum 3-of-5: the five TD 1 models. OK: the kept value equals the reference (`-` when the vote abstains).\n\n"
        + "\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    print(f"\n2-of-3: {sum(r['panel_2_of_3_matches_reference'] == 'yes' for r in table)} right, "
          f"{sum(r['panel_2_of_3_matches_reference'] == 'NO' for r in table)} wrong, "
          f"{sum(r['panel_2_of_3_matches_reference'] == '-' for r in table)} abstentions")
    print(f"3-of-5: {sum(r['quorum_3_of_5_matches_reference'] == 'yes' for r in table)} right, "
          f"{sum(r['quorum_3_of_5_matches_reference'] == 'NO' for r in table)} wrong, "
          f"{sum(r['quorum_3_of_5_matches_reference'] == '-' for r in table)} abstentions")
    print("decision changes on:", [r["case_id"] for r in table if r["decision_changes"]])


if __name__ == "__main__":
    main()
