"""TD 2 step 1: the twenty-question comparison table, 2-of-3 versus 3-of-5.

Usage (from the repository root):  python3 td2/A-quorum/td2_vote_table.py
Reads traces-td1.csv (stored TD 1 traces, nature real) and reference-td1.csv.
Calls OUR Orchestrateur.vote_k_sur_n from skeleton-multi-llm-en.py for both quorums:
  - 2-of-3: the fixed panel of atelier-vote.py (gpt-oss-120b, Cohere, Qwen), k = 2;
  - 3-of-5: all five TD 1 models, k = 3.
The reference is compared AFTER each decision; the vote never receives it.
Prints the Markdown table pasted in reports/td2.md (section 2); writes no file.
"""
import csv
import importlib.util
import sys
from pathlib import Path
from types import SimpleNamespace

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

PANEL_3 = [
    ("groq", "openai/gpt-oss-120b"),
    ("openrouter", "cohere/north-mini-code:free"),
    ("groq", "qwen/qwen3.8-27b"),
]
PANEL_5 = PANEL_3 + [
    ("groq", "openai/gpt-oss-20b"),
    ("openrouter", "dots-studio/dots-3-note-preview:free"),
]
SHORT = {
    "openai/gpt-oss-120b": "120B",
    "openai/gpt-oss-20b": "20B",
    "qwen/qwen3.8-27b": "Qwen",
    "cohere/north-mini-code:free": "Cohere",
    "dots-studio/dots-3-note-preview:free": "Dots",
}


def load_vote():
    spec = importlib.util.spec_from_file_location("student_skeleton", ROOT / "skeleton-multi-llm-en.py")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return lambda proposals, k: module.Orchestrateur.vote_k_sur_n(None, proposals, k)


def proposals_for(rows, case, panel):
    """Same rule as atelier-vote.py: last attempt per member; an invalid or missing one keeps its place without a vote."""
    selected = {}
    for row in rows:
        key = (row["provider"], row["model_requested"])
        if row["case_id"] == case and row["nature"] == "real" and key in panel:
            selected[key] = row
    proposals = []
    for provider, model in panel:
        row = selected.get((provider, model), {})
        value = row.get("value", "")
        valid = row.get("verdict") in {"correct", "incorrect"} and value not in {None, ""}
        proposals.append(SimpleNamespace(provider=provider, model_requested=model,
                                         value=int(value) if valid else None,
                                         verdict="executed" if valid else "error"))
    return proposals


def describe(decision, reference):
    if not decision["consensus"]:
        return "abstain", "", "n/a"
    agrees = "yes" if decision["value"] == reference else "**no**"
    return "consensus", decision["value"], agrees


def main():
    vote = load_vote()
    with open(ROOT / "traces-td1.csv", encoding="utf-8", newline="") as f:
        rows = list(csv.DictReader(f))
    with open(ROOT / "reference-td1.csv", encoding="utf-8", newline="") as f:
        references = {r["case_id"]: int(r["revenue_cents"]) for r in csv.DictReader(f)}

    table = []
    for case in sorted(references):
        props5 = proposals_for(rows, case, PANEL_5)
        d3 = vote(proposals_for(rows, case, PANEL_3), 2)
        d5 = vote(props5, 3)
        ref = references[case]
        values = ", ".join(f"{SHORT[p.model_requested]}={p.value if p.value is not None else 'error'}" for p in props5)
        r3, r5 = describe(d3, ref), describe(d5, ref)
        changed = (d3["consensus"], d3["value"]) != (d5["consensus"], d5["value"])
        table.append({"case_id": case, "reference": ref,
                      "decision_2of3": r3[0], "value_2of3": r3[1], "votes_2of3": d3["votes"], "agrees_2of3": r3[2].strip("*"),
                      "decision_3of5": r5[0], "value_3of5": r5[1], "votes_3of5": d5["votes"], "agrees_3of5": r5[2].strip("*"),
                      "changed": "yes" if changed else "", "five_values": values,
                      "_md": (r3, r5)})

    lines = [
        "# TD 2 step 1: 2-of-3 versus 3-of-5 on the twenty questions",
        "",
        "Generated by `python3 td2/A-quorum/td2_vote_table.py` from `traces-td1.csv` (nature real, last attempt per model) "
        "and `reference-td1.csv`. 2-of-3 = fixed panel 120B, Cohere, Qwen (k = 2); 3-of-5 = the five TD 1 models (k = 3). "
        "The reference is compared after the decision.",
        "",
        "| Case | Reference | 2-of-3 decision | value | votes | = ref | 3-of-5 decision | value | votes | = ref | Changed | Values of the five models |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in table:
        (d3, v3, a3), (d5, v5, a5) = r["_md"]
        lines.append(f"| {r['case_id']} | {r['reference']} | {d3} | {v3} | {r['votes_2of3']} | {a3} | "
                     f"{d5} | {v5} | {r['votes_3of5']} | {a5} | {'**yes**' if r['changed'] else ''} | {r['five_values']} |")

    def count(prefix):
        consensus = [r for r in table if r[f"decision_{prefix}"] == "consensus"]
        right = sum(r[f"agrees_{prefix}"] == "yes" for r in consensus)
        return len(consensus), right, len(consensus) - right, len(table) - len(consensus)

    lines += ["", "| Quorum | Consensus | of which right | of which wrong | Abstentions |", "|---|---|---|---|---|"]
    for label, prefix in [("2-of-3", "2of3"), ("3-of-5", "3of5")]:
        c, ok, ko, ab = count(prefix)
        lines.append(f"| {label} | {c} | {ok} | {ko} | {ab} |")
    lines += ["", "Questions where the decision changes: "
              + (", ".join(r["case_id"] for r in table if r["changed"]) or "none") + "."]
    print("\n".join(lines))


if __name__ == "__main__":
    main()
