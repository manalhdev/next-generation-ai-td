"""TD 2 step 3: exact TD 1 accuracy rate of each model on each question family.

Usage (from the repository root):  python3 tools/td2_family_rates.py
Reads questions-td1.json (question types) and model-question-comparison-en.csv (TD 1 final results).
Writes results/family-rates-td2.md.
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CODES = {"period": "F1", "age on a reference date": "F2", "age at the time of the order": "F2b", "product list": "F3"}


def family_of(question_type):
    return "+".join(CODES[part.strip()] for part in question_type.split("+"))


def load_rates():
    questions = json.loads((ROOT / "questions-td1.json").read_text(encoding="utf-8"))["questions"]
    families = {}
    for q in questions:
        families.setdefault(family_of(q["type"]), []).append(q["id"])
    with open(ROOT / "model-question-comparison-en.csv", encoding="utf-8", newline="") as f:
        status = {(r["model_id"], r["case_id"]): r["status"] for r in csv.DictReader(f)}
    models = sorted({model for model, _ in status})
    rates = {}
    for family, cells in families.items():
        for model in models:
            failed = [c for c in cells if status[(model, c)] != "correct"]
            rates[(family, model)] = (len(cells) - len(failed), len(cells), failed)
    return families, models, rates


def main():
    families, models, rates = load_rates()
    order = ["F1", "F3", "F2", "F2b", "F1+F2", "F2+F3", "F1+F2+F3", "F1+F2b"]
    names = [m.split(":", 1)[1] for m in models]
    lines = ["# TD 2 — TD 1 accuracy per question family",
             "",
             "Generated by `tools/td2_family_rates.py` from `model-question-comparison-en.csv` (100 real TD 1 cells) and `questions-td1.json`. "
             "F1 period, F2 completed age at a reference date, F2b age at the time of the order, F3 product list.",
             "",
             "| Family | TD 1 cells | " + " | ".join(names) + " |",
             "|---|---|" + "---|" * len(models)]
    for family in order:
        cells = ", ".join(families[family])
        row = []
        for model in models:
            ok, total, failed = rates[(family, model)]
            row.append(f"{ok}/{total}" + (f" (fails {', '.join(failed)})" if failed else ""))
        lines.append(f"| {family} | {cells} | " + " | ".join(row) + " |")
    age_cells = [c for f in order if "F2" in f.split("+") for c in families[f]]
    lines += ["", f"Any question with an age at a reference date ({', '.join(age_cells)}):", ""]
    for model in models:
        ok = sum(rates[(f, model)][0] for f in order if "F2" in f.split("+"))
        failed = [c for f in order if "F2" in f.split("+") for c in rates[(f, model)][2]]
        lines.append(f"- {model.split(':', 1)[1]}: {ok}/{len(age_cells)}" + (f" (fails {', '.join(failed)})" if failed else ""))
    (ROOT / "results").mkdir(exist_ok=True)
    (ROOT / "results" / "family-rates-td2.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
