"""Build td1/verifications-td1.md: every TD 1 reference, who wrote it, who checked it and how.

Usage (from the repository root):  python3 tools/build_verifications.py
Sources: reference-td1.csv (queries, authors, checks), td1/*.sql (queries kept as files),
prep/td1-plan.md (planned checker), kit-docs/reference-values-td1-en.md (published values).
The file is regenerated from these sources: edit reference-td1.csv, not the generated file.
"""
import csv
import re
import sqlite3
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "td1" / "verifications-td1.md"


def published_values():
    text = (ROOT / "kit-docs" / "reference-values-td1-en.md").read_text(encoding="utf-8")
    return dict(re.findall(r"^\| (C\d\d) \|.*?\| (\d+) \|[^|]*\|\s*$", text, re.M))


def planned_checkers():
    text = (ROOT / "prep" / "td1-plan.md").read_text(encoding="utf-8")
    plan = {}
    for member, checks in re.findall(r"^\| ([^|]+?) \| [^|]+ \| ([C0-9, ]+) \|$", text, re.M):
        for case_id in re.findall(r"C\d\d", checks):
            plan[case_id] = member.split(" (")[0]
    return plan


def sql_files():
    files = {}
    for path in sorted((ROOT / "td1").glob("*.sql")):
        author = subprocess.run(["git", "log", "--format=%an", "--reverse", "--", str(path)],
                                capture_output=True, text=True, cwd=ROOT).stdout.split("\n")[0]
        files[path.stem.upper()] = (path.relative_to(ROOT).as_posix(), author or "not committed")
    return files


def run(con, sql):
    try:
        return str(con.execute(sql).fetchone()[0])
    except Exception as exc:
        return f"error: {exc}"


def main():
    published, plan, files = published_values(), planned_checkers(), sql_files()
    con = sqlite3.connect(f"file:{ROOT / 'data' / 'boutique.sqlite'}?mode=ro", uri=True)
    with open(ROOT / "reference-td1.csv", newline="", encoding="utf-8") as f:
        refs = {r["case_id"]: r for r in csv.DictReader(f)}

    rows, todo = [], []
    for case_id in sorted(published):
        r = refs.get(case_id, {})
        sql, value = (r.get("sql") or "").strip(), (r.get("revenue_cents") or "").strip()
        writer = (r.get("written_by") or "").strip()
        checker = (r.get("checked_by") or "").strip()
        method = (r.get("check_method") or "").strip()
        file, file_author = files.get(case_id, ("", ""))
        executed = run(con, sql) if sql else ""

        if not sql:
            status = "missing query in reference-td1.csv"
            todo.append(f"{case_id}: {writer or 'author'} adds the query and value to reference-td1.csv"
                        + (f" (query exists in `{file}`, by {file_author})" if file else ""))
        elif not value:
            status = "query present, value missing"
            todo.append(f"{case_id}: {writer or 'author'} records the value returned by the query ({executed})")
        elif executed != value:
            status = f"query returns {executed}, recorded {value}"
            todo.append(f"{case_id}: query and recorded value disagree")
        elif value != published[case_id]:
            status = "differs from the published value"
            todo.append(f"{case_id}: find the convention error and note the cause in reports/td1.md")
        elif not checker or "pending" in checker:
            status = "correct, peer check pending"
            todo.append(f"{case_id}: {plan.get(case_id, 'a second member')} cross-checks with a different method")
        else:
            status = "complete"
        rows.append((case_id, writer or file_author, value or "-", published[case_id],
                     "yes" if value == published[case_id] else ("-" if not value else "no"),
                     checker or f"planned: {plan.get(case_id, '?')}", method or "-", file or "-", status))

    done = sum(r[-1] == "complete" for r in rows)
    lines = [
        "# TD 1 — verification of the twenty references",
        "",
        "Generated by `tools/build_verifications.py` from `reference-td1.csv`, `td1/*.sql`, `prep/td1-plan.md`",
        "and the values published by the instructors (`kit-docs/reference-values-td1-en.md`). Do not edit by hand.",
        "",
        "Each value must come from the member's own SQL query, run on `data/boutique.sqlite`, and be checked by",
        "another member with a different method. The published values are used only to compare.",
        "",
        f"**{done}/20 complete** (own query, correct value, peer check done).",
        "",
        "| Case | Written by | Our value | Published | Equal | Checked by | Check method | Query file | Status |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    lines += ["| " + " | ".join(str(c).replace("|", "/") for c in row) + " |" for row in rows]
    lines += ["", "## Check scripts", "",
              "| Script | Author | Checks |", "|---|---|---|",
              "| `td1/crosscheck_manal.py` | manalhdev | C15, C16, C19: Python on the CSV files, no SQL |",
              "| `crosscheck_references_axel.py` | axel12334556 | C02, C13, C14 (own) and C08, C09, C11: second SQL + Python on CSV |",
              "| `refs_TasB.py` | TasB | C02, C13, C14 (Axel) and own C15, C16, C19: own SQL + Python on CSV |",
              "| `tools/compare_references.py` | manalhdev | the twenty values against the published table |",
              "", "## Still to do", ""]
    lines += [f"- {t}" for t in todo] or ["- nothing"]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {done}/20 complete, {len(todo)} item(s) to do")


if __name__ == "__main__":
    main()
