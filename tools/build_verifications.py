"""Build the two TD 1 summary files from reference-td1.csv.

- td1/verifications-td1.md: every reference, who wrote it, who checked it and how.
- td1/queries-td1.sql: the twenty reference queries in one file, runnable with sqlite3.

Usage (from the repository root):  python3 tools/build_verifications.py
Sources: reference-td1.csv (queries, authors, checks), questions-td1.json (question text),
prep/td1-plan.md (planned checker), kit-docs/reference-values-td1-en.md (published values).
Both files are regenerated from these sources: edit reference-td1.csv, not the generated files.
"""
import csv
import json
import re
import sqlite3
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "td1" / "verifications-td1.md"
QUERIES = ROOT / "td1" / "queries-td1.sql"

CHECK_SCRIPTS = [
    ("td1/crosscheck_references_axel.py", "axel12334556", "axel12334556",
     "own C02, C13, C14 and C08, C09, C11 (lorentejla): second SQL + Python on CSV"),
    ("refs_TasB.py", "TasB", "TasB", "C02, C13, C14 (axel12334556) and own C15, C16, C19: own SQL + Python on CSV"),
    ("td1/crosscheck_manal.py", "manalhdev", "manalhdev", "C15, C16, C19 (TasB): Python on CSV, no SQL"),
    ("td1/crosscheck_c03_c06_c07.py", "Daiki4529", "Daiki4529", "C03, C06, C07 (ines729): Python on CSV, no SQL"),
    ("td1/crosscheck_ines.py", "manalhdev (AI-assisted)", "ines729", "C01, C05, C12 (Marieseka): Python on CSV, no SQL"),
    ("td1/crosscheck_marie.py", "manalhdev (AI-assisted)", "Marieseka", "C04, C20 (Daiki4529): Python on CSV, no SQL"),
    ("td1/crosscheck_lorentejla.py", "lorentejla", "lorentejla", "C10, C17, C18 (manalhdev): SQL re-run + Python on CSV"),
    ("tools/compare_references.py", "manalhdev", "anyone", "runs the twenty queries, compares with the published values"),
]


def missing_scripts(method):
    """Scripts cited in a check_method that are not in the repository."""
    return [p for p in re.findall(r"[\w./-]+\.py", method) if not (ROOT / p).exists()]


def published_values():
    text = (ROOT / "kit-docs" / "reference-values-td1-en.md").read_text(encoding="utf-8")
    return dict(re.findall(r"^\| (C\d\d) \|.*?\| (\d+) \|[^|]*\|\s*$", text, re.M))


def planned_checkers():
    text = (ROOT / "prep" / "td1-plan.md").read_text(encoding="utf-8")
    plan = {}
    for member, checks in re.findall(r"^\| ([^|]+?) \| [^|]+ \| ([C0-9, ]+) \|$", text, re.M):
        for case_id in re.findall(r"C\d\d", checks):
            plan[case_id] = member.split(" (")[0]
    return plan


def run(con, sql):
    try:
        return str(con.execute(sql).fetchone()[0])
    except Exception as exc:
        return f"error: {exc}"


def write_queries(refs, questions, published):
    lines = [
        "-- TD 1: the twenty reference queries, one per question.",
        "-- Generated by tools/build_verifications.py from reference-td1.csv. Do not edit by hand.",
        "-- Run from the repository root: sqlite3 data/boutique.sqlite < td1/queries-td1.sql",
        "-- It prints the twenty values, C01 to C20, each in euro cents excluding VAT.",
        "",
    ]
    for case_id in sorted(published):
        r = refs.get(case_id, {})
        q = questions.get(case_id, {})
        sql = (r.get("sql") or "").strip().rstrip(";").strip()
        lines += [
            f"-- {case_id} ({q.get('type', '?')}) {q.get('question', '')}",
            f"-- written by {r.get('written_by') or '?'}, checked by {r.get('checked_by') or '?'}, "
            f"value {r.get('revenue_cents') or '?'} (published {published[case_id]})",
            (sql or "SELECT NULL AS revenue_cents") + ";",
            "",
        ]
    QUERIES.write_text("\n".join(lines), encoding="utf-8")


def main():
    published, plan = published_values(), planned_checkers()
    con = sqlite3.connect(f"file:{ROOT / 'data' / 'boutique.sqlite'}?mode=ro", uri=True)
    with open(ROOT / "reference-td1.csv", newline="", encoding="utf-8") as f:
        refs = {r["case_id"]: r for r in csv.DictReader(f)}
    questions = {q["id"]: q for q in json.loads((ROOT / "questions-td1.json").read_text(encoding="utf-8"))["questions"]}

    rows, todo = [], []
    for case_id in sorted(published):
        r = refs.get(case_id, {})
        sql, value = (r.get("sql") or "").strip(), (r.get("revenue_cents") or "").strip()
        writer = (r.get("written_by") or "").strip()
        checker = (r.get("checked_by") or "").strip()
        method = (r.get("check_method") or "").strip()
        executed = run(con, sql) if sql else ""

        if not sql:
            status = "missing query in reference-td1.csv"
            todo.append(f"{case_id}: {writer or 'author'} adds the query and value to reference-td1.csv")
        elif not value:
            status = "query present, value missing"
            todo.append(f"{case_id}: {writer or 'author'} records the value returned by the query ({executed})")
        elif executed != value:
            status = f"query returns {executed}, recorded {value}"
            todo.append(f"{case_id}: query and recorded value disagree")
        elif value != published[case_id]:
            status = "differs from the published value"
            todo.append(f"{case_id}: find the convention error and note the cause in reports/td1.md")
        elif not checker or "pending" in checker:
            status = "correct, peer check pending"
            todo.append(f"{case_id}: {plan.get(case_id, 'a second member')} cross-checks with a different method")
        elif missing_scripts(method):
            status = "check script missing from the repository: " + ", ".join(missing_scripts(method))
            todo.append(f"{case_id}: {checker} commits " + ", ".join(f"`{m}`" for m in missing_scripts(method)))
        else:
            status = "complete"
        rows.append((case_id, writer or "-", value or "-", published[case_id],
                     "yes" if value == published[case_id] else ("-" if not value else "no"),
                     checker or f"planned: {plan.get(case_id, '?')}", method or "-", status))

    done = sum(r[-1] == "complete" for r in rows)
    lines = [
        "# TD 1 — verification of the twenty references",
        "",
        "Generated by `tools/build_verifications.py` from `reference-td1.csv`, `prep/td1-plan.md`",
        "and the values published by the instructors (`kit-docs/reference-values-td1-en.md`). Do not edit by hand.",
        "The twenty queries themselves are in `reference-td1.csv` and, readable, in `td1/queries-td1.sql`.",
        "",
        "Each value must come from the member's own SQL query, run on `data/boutique.sqlite`, and be checked by",
        "another member with a different method. The published values are used only to compare.",
        "",
        f"**{done}/20 complete** (own query, correct value, peer check done).",
        "",
        "| Case | Written by | Our value | Published | Equal | Checked by | Check method | Status |",
        "|---|---|---|---|---|---|---|---|",
    ]
    lines += ["| " + " | ".join(str(c).replace("|", "/") for c in row) + " |" for row in rows]
    lines += ["", "## Check scripts", "",
              "| Script | Written by | Run by | Checks | |", "|---|---|---|---|---|"]
    lines += [f"| `{s}` | {w} | {r} | {c} | " + ("present" if (ROOT / s).exists() else "**not in the repository yet**") + " |"
              for s, w, r, c in CHECK_SCRIPTS]
    lines += ["", "## Replay", "", "```bash",
              "python3 tools/compare_references.py               # runs the twenty queries, compares with published values",
              "sqlite3 data/boutique.sqlite < td1/queries-td1.sql # the same twenty queries with the sqlite3 shell",
              "python3 td1/crosscheck_manal.py                   # each check script prints OK / MATCH per question",
              "```", "",
              "`td1/crosscheck_references_axel.py` rewrites its rows of `reference-td1.csv` when it runs: "
              "run it on a copy, or restore the file with `git checkout -- reference-td1.csv` afterwards.",
              "", "## Still to do", ""]
    lines += [f"- {t}" for t in todo] or ["- nothing"]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    write_queries(refs, questions, published)
    print(f"{OUT.relative_to(ROOT)}: {done}/20 complete, {len(todo)} item(s) to do")
    print(f"{QUERIES.relative_to(ROOT)}: {len(published)} queries")


if __name__ == "__main__":
    main()
